// Builds database/schema.sql from the Drizzle migrations — for hosts where you
// prefer importing through phpMyAdmin instead of running `npm run db:migrate`.
// It also records the migrations as applied, so db:migrate stays in sync later.
//   npm run db:sql

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "../..");
const journal = JSON.parse(fs.readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8")) as { entries: { tag: string; when: number }[] };

let out = `-- TraceCoreLab database schema (generated by \`npm run db:sql\` — do not edit by hand)
-- Import into an EMPTY database created with utf8mb4, e.g.:
--   CREATE DATABASE tracecorelab CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
-- Then run \`npm run db:seed\` and \`npm run admin:create\` from your computer,
-- or create the first admin with the SQL at the end of the README.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

`;
const applied: string[] = [];
for (const entry of journal.entries) {
  const file = fs.readFileSync(path.join(root, "drizzle", `${entry.tag}.sql`), "utf8");
  out += `-- ${entry.tag}\n${file.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean).join(";\n").replace(/;;/g, ";")};\n\n`;
  applied.push(`('${createHash("sha256").update(file).digest("hex")}', ${entry.when})`);
}
out += `SET FOREIGN_KEY_CHECKS = 1;

-- Mark the migrations above as applied for \`npm run db:migrate\`.
CREATE TABLE IF NOT EXISTS \`__drizzle_migrations\` (id serial primary key, hash text not null, created_at bigint);
INSERT INTO \`__drizzle_migrations\` (\`hash\`, \`created_at\`) VALUES ${applied.join(", ")};
`;

fs.mkdirSync(path.join(root, "database"), { recursive: true });
fs.writeFileSync(path.join(root, "database/schema.sql"), out);
console.log(`✓ Wrote database/schema.sql (${journal.entries.length} migration${journal.entries.length === 1 ? "" : "s"})`);
