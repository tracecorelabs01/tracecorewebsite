const NAMES: Record<Provider, string> = { google: "Google", discord: "Discord" };

export function SocialSignIn({ providers, next, className }: { providers: Provider[]; next: string; className?: string }) {
  if (!providers.length) return null;
  return (
    <div className={cn("grid gap-3 sm:grid-cols-2", className)}>
      {providers.map((p) => (
        <a
          key={p}
          href={`/api/auth/${p}/start?${new URLSearchParams({ next })}`}
          className="flex h-12 items-center justify-center gap-2.5 rounded-xl border border-line-strong bg-ink-900 px-4 text-sm font-medium transition-colors hover:border-blaze"
        >
          <svg viewBox="0 0 24 24" aria-hidden="true" className="size-4 fill-current">
            <path d={ICONS[p]} />
          </svg>
          Continue with {NAMES[p]}
        </a>
      ))}
    </div>
  );
}
