/** Countries under comprehensive sanctions: not offered at checkout unless Settings say otherwise. */
export const EMBARGOED = ["BY", "CU", "IR", "KP", "RU", "SY"];

/** The countries checkout offers, as [code, name], with the excluded codes removed. */
export function shipCountries(excluded: readonly string[]) {
  const skip = new Set(excluded);
  return ALL_COUNTRIES.filter(([code]) => !skip.has(code));
}

/** The names checkout and the address book list (and store). */
export const shipCountryNames = (excluded: readonly string[]) => shipCountries(excluded).map(([, name]) => name);

/** ISO codes the store ships to, for structured data and the product feed. */
export const shipCountryCodes = (excluded: readonly string[]) => shipCountries(excluded).map(([code]) => code);
